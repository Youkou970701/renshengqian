export function careerPhrase(name,changed=false){return phrases[name]?.[Number(changed)]??`${changed?'转做':'做'}${name}`;}
export function careerYearsPhrase(name,years){
 if(['务农','农民'].includes(name))return `前后种了${years}年地`;
 if(['个体户','个体经营者','店主','网店店主','小厂经营者'].includes(name))return `前后经营了${years}年生意`;
 if(name==='军人')return `前后当了${years}年兵`;
 if(name==='自由职业者')return `前后自由接活${years}年`;
 return `前后做了${years}年${name}`;
}
