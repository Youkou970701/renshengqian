// 性别 × 城乡
export const sexPlace = s => `${s.sex === 'female' ? 'f' : 'm'}-${RURAL(s) ? 'rural' : 'urban'}`
// 养老：农村 / 城镇工薪 / 本科以上 / 体制内
const PUBLIC_JOBS = ['公务员', '事业编', '教师', '医护', '军人']
// 晚年按「现在住在哪、做过什么」分：体制内 / 住在村里 / 本科以上 / 城镇工薪（农村户口但在城里干了一辈子的人归城镇工薪）
